<?php

declare(strict_types=1);

namespace Drupal\Tests\badcamp_sponsors\Kernel;

use Drupal\KernelTests\KernelTestBase;
use Drupal\node\Entity\Node;
use Drupal\node\NodeInterface;
use Drupal\pathauto\Entity\PathautoPattern;
use Drupal\pathauto\PathautoState;
use PHPUnit\Framework\Attributes\Group;

/**
 * Tests the Pathauto alias behaviour (AC 8).
 */
#[Group('badcamp_sponsors')]
class PathautoTest extends KernelTestBase {

  /**
   * {@inheritdoc}
   */
  protected static $modules = ['system', 'user'];

  /**
   * {@inheritdoc}
   */
  protected function setUp(): void {
    parent::setUp();
    $this->installEntitySchema('user');
    // System config provides the date formats the token system needs when
    // pathauto builds [node:title] aliases on node save.
    $this->installConfig(['user', 'system']);
    $this->container->get('module_installer')->install(['badcamp_sponsors']);
  }

  /**
   * Creates and saves a sponsor node.
   */
  protected function createSponsor(string $title): NodeInterface {
    $sponsor = Node::create([
      'type' => 'sponsor',
      'title' => $title,
      'status' => 1,
    ]);
    $sponsor->save();
    return $sponsor;
  }

  /**
   * Creates and saves a campaign node.
   */
  protected function createCampaign(string $title): NodeInterface {
    $campaign = Node::create([
      'type' => 'campaign',
      'title' => $title,
      'status' => 1,
    ]);
    $campaign->save();
    return $campaign;
  }

  /**
   * Creates and saves a coupon node.
   */
  protected function createCoupon(string $code, NodeInterface $sponsor, NodeInterface $campaign): NodeInterface {
    $coupon = Node::create([
      'type' => 'coupon',
      'title' => 'Placeholder title',
      'status' => 1,
      'field_coupon_code' => $code,
      'field_coupon_sponsor' => ['target_id' => $sponsor->id()],
      'field_coupon_campaign' => ['target_id' => $campaign->id()],
    ]);
    $coupon->save();
    return $coupon;
  }

  /**
   * Returns all aliases registered for a node system path.
   *
   * @return string[]
   *   The alias strings.
   */
  protected function getAliases(string $path): array {
    $aliases = $this->container->get('entity_type.manager')
      ->getStorage('path_alias')
      ->loadByProperties(['path' => $path]);
    return array_values(array_map(
      static fn($alias): string => $alias->getAlias(),
      $aliases
    ));
  }

  /**
   * Tests that sponsors and campaigns get their singular aliases.
   */
  public function testSponsorAndCampaignAliases(): void {
    $sponsor = $this->createSponsor('Acme Corp');
    $this->assertSame(
      ['/sponsor/acme-corp'],
      $this->getAliases('/node/' . $sponsor->id()),
      'Sponsors get a /sponsor/<name> alias.'
    );

    $campaign = $this->createCampaign('Fall Blast');
    $this->assertSame(
      ['/campaign/fall-blast'],
      $this->getAliases('/node/' . $campaign->id()),
      'Campaigns get a /campaign/<name> alias.'
    );
  }

  /**
   * Tests that coupons get no alias at all.
   */
  public function testCouponsGetNoAlias(): void {
    $sponsor = $this->createSponsor('Acme Corp');
    $campaign = $this->createCampaign('Fall Blast');
    $coupon = $this->createCoupon('SAVE20', $sponsor, $campaign);

    $this->assertSame(
      [],
      $this->getAliases('/node/' . $coupon->id()),
      'Coupons get no path alias.'
    );

    // No catch-all pattern creates a /coupon/... alias either.
    $all = $this->container->get('entity_type.manager')
      ->getStorage('path_alias')
      ->loadMultiple();
    $this->assertNotEmpty($all, 'Sanity: sponsor and campaign aliases exist.');
    foreach ($all as $alias) {
      $this->assertStringStartsNotWith(
        '/coupon',
        $alias->getAlias(),
        'No coupon alias is generated by any pattern.'
      );
    }
  }

  /**
   * Tests that a site-wide catch-all pattern cannot alias coupons.
   *
   * Post-audit rework of AC 8: the Drupal CMS starter site ships `menu_path`,
   * a pattern with NO selection criteria at weight 10, so it matches every
   * node bundle. This suite's environment installs only the module's two
   * bundle-specific patterns, which is why the original tests could not see
   * the live-site violation (observed: a coupon aliased to
   * /save20-acme-corp-fall-blast). This test reproduces the live shape.
   */
  public function testCatchAllPatternDoesNotAliasCoupons(): void {
    // Reproduce the live site's catch-all: enabled, no selection criteria,
    // heavier than the module's bundle-specific patterns (weight 0).
    PathautoPattern::create([
      'id' => 'catch_all',
      'label' => 'Catch-all',
      'type' => 'canonical_entities:node',
      'pattern' => '/[node:title]',
      'weight' => 10,
      'status' => TRUE,
    ])->save();

    // The bundle-specific sponsor pattern (weight 0) must beat the catch-all
    // (weight 10): PathautoGenerator::getPatternByEntityType() sorts patterns
    // by weight and getPatternByEntity() returns the first that applies.
    $sponsor = $this->createSponsor('Acme Corp');
    $this->assertSame(
      ['/sponsor/acme-corp'],
      $this->getAliases('/node/' . $sponsor->id()),
      'Sponsors keep their /sponsor/<name> alias despite the catch-all.'
    );

    // Coupons must get no alias at all, even though the catch-all matches
    // them. This is the RED assertion before the presave fix.
    $campaign = $this->createCampaign('Fall Blast');
    $coupon = $this->createCoupon('SAVE20', $sponsor, $campaign);
    $this->assertSame(
      [],
      $this->getAliases('/node/' . $coupon->id()),
      'Coupons get no alias even when a catch-all pattern matches them.'
    );

    // Pin the mechanism: the presave hook must mark the coupon's path field
    // SKIP, the canonical pathauto seam (PathautoGenerator.php:393 skips when
    // the state is not PathautoState::CREATE), so editors and bulk updates
    // cannot alias the coupon later either.
    $this->assertSame(
      PathautoState::SKIP,
      $coupon->path->pathauto,
      "The coupon's path field is marked PathautoState::SKIP."
    );
    $this->assertSame(
      PathautoState::SKIP,
      \Drupal::keyValue('pathauto_state.node')->get($coupon->id()),
      'The SKIP state is persisted, so later saves and bulk updates skip too.'
    );
  }

}
